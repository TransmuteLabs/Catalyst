#!/usr/bin/env bash
# Стенд оснастки приёмки рендера (#258): предмет -- tests/scripts/render-tree.py.
#
# Прибор запускает мод БЕЗ терминала (изолированный корень + безголовый
# node-субпроцесс --experimental-strip-types) и снимает ОБЕ поверхности:
# возврат обработчика рендера (дерево) и вызовы $.ui.status (строка; очистка
# -- событие), приводит к устойчивому виду (подвижные величины -- метками
# рода) и даёт сравнение с именованными отказами
# (ПРОПАЛ/ЛИШНИЙ/ФОРМА/ЗНАЧЕНИЕ).
# Зубы гоняются на СИНТЕТИЧЕСКИХ модах, генерируемых на время прогона:
# прибор не пинит ни имён поверхностей, ни имён событий предмета -- при боевом
# снятии событие рендера задаётся ручкой (capture --event ...). Живой прогон
# рендера -- отдельный акт оператора; безголовый `claude -p` рендер не зовёт
# (замер 2026-09-19: свидетель statusLine не создан, изолированный дом без
# учётки сессию не стартует), дорога снятия -- прямой вызов обработчика,
# полная редакция в Catalyst-programs/2026-09-18-refs-census-hud/HARNESS-render-tree.md.
#
# CONSTRAINT: стенд НИКОГДА не читает боевой ~/.claude и не зовёт бинарник
# claude -- предмет батареи Instrument плюс синтетика; изоляция доказывается
# самой батареей (корень прогона и env-дом внутри её временного каталога,
# fs-гвард отказывает запись за границей поимённо).
#
# Коды по контракту агрегатора (tests/run-all.sh):
#   0 -- зелёный: самопроверка доказала пинное число зубов («зубов N»),
#        все случаи зелёные;
#   1 -- КРАСЕН: зуб или случай ответил провалом;
#   2 -- ПРИБОР НЕДОСТУПЕН: нет python3/инструмента/node, батарея рухнула;
#   3 -- НЕ ИЗМЕРЕНО: rc=0 без доказанного числа зубов либо число зубов или
#        случаев разошлось с пином (зуб выпал или прибавился).
set -u

# CONSTRAINT: неизвестный аргумент отвергается ДО любой работы (форма
# test-judge-serves.sh / test-effort-layers.sh).
if [ "$#" -ne 0 ]; then
  printf 'ОТКАЗ ПРИБОРА: неизвестный аргумент: %s; стенд принимает только запуск без аргументов\n' "$1" >&2
  exit 2
fi

# Пин числа зубов прибора: 7 обязательных набора брифа, плюс зуб против
# вакуумной зелени, плюс 5 зубов поверхностей статусной строки (поправка брифа
# 2026-09-19: строка -- ВЫЗОВ $.ui.status, очистка -- событие; несущий зуб --
# «только строка и пустой возврат» не есть «пусто»). Самопроверка печатает
# фактически прошедшее число, расхождение в любую сторону -- rc=3.
EXPECTED_TEETH=13
# Пин числа случаев: именованные отказы сравнения и состояния без дерева.
EXPECTED_CASES=8

if ! command -v python3 >/dev/null 2>&1; then
  printf 'ПРИБОР НЕДОСТУПЕН: нет python3\n' >&2
  exit 2
fi

HERE=$(cd "$(dirname "$0")" && pwd) || exit 2
TOOL="$HERE/render-tree.py"
if [ ! -f "$TOOL" ]; then
  printf 'ПРИБОР НЕДОСТУПЕН: нет %s\n' "$TOOL" >&2
  exit 2
fi

OUT=$(python3 "$TOOL" --self-check 2>&1)
RC=$?
if [ "$RC" -eq 1 ]; then
  printf 'КРАСЕН render-tree --self-check (rc=1):\n%s\n' "$OUT"
  exit 1
fi
if [ "$RC" -ne 0 ]; then
  printf 'ПРИБОР НЕДОСТУПЕН: render-tree --self-check rc=%s:\n%s\n' "$RC" "$OUT" >&2
  exit 2
fi

# rc=0 обязан ДОКАЗЫВАТЬ число зубов строкой «зубов N» (ПУСТО != НОЛЬ).
TEETH=''
if [[ "$OUT" =~ зубов[[:space:]]+([0-9]+) ]]; then
  TEETH="${BASH_REMATCH[1]}"
fi
if [ -z "$TEETH" ]; then
  printf 'НЕ ИЗМЕРЕНО: rc=0 без доказанного числа зубов (в выводе нет «зубов N»):\n%s\n' "$OUT"
  exit 3
fi
if [ "$TEETH" -ne "$EXPECTED_TEETH" ]; then
  printf 'НЕ ИЗМЕРЕНО: зубов в выводе %s, а стенд ожидает %s (зуб выпал или прибавился):\n%s\n' \
    "$TEETH" "$EXPECTED_TEETH" "$OUT"
  exit 3
fi

CASES=''
GREEN=''
if [[ "$OUT" =~ случаев[[:space:]]+([0-9]+),[[:space:]]*зелёных[[:space:]]+([0-9]+) ]]; then
  CASES="${BASH_REMATCH[1]}"
  GREEN="${BASH_REMATCH[2]}"
fi
if [ -z "$CASES" ] || [ -z "$GREEN" ]; then
  printf 'НЕ ИЗМЕРЕНО: счёт случаев не разобран:\n%s\n' "$OUT"
  exit 3
fi
if [ "$CASES" -ne "$EXPECTED_CASES" ] || [ "$GREEN" -ne "$CASES" ]; then
  printf 'НЕ ИЗМЕРЕНО: случаев %s (ожидается %s), зелёных %s -- случай выпал или провалился:\n%s\n' \
    "$CASES" "$EXPECTED_CASES" "$GREEN" "$OUT"
  exit 3
fi

printf '%s\n' "$OUT"
exit 0
