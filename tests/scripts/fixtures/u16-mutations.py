for name, old, new, mode, expected in MUTATIONS:
    source = (ROOT / "tests/scripts/test-dispatch-gate.sh").read_text() if name == "lim17-double-call" else SOURCE
    count = source.count(old)
    if count != 1:
        raise SystemExit(f"REFUSE {name}: mutation anchor count={count}, expected=1")
    mutated = source.replace(old, new, 1)
    if mutated == source:
        raise SystemExit(f"REFUSE {name}: mutation did not change the source")
    with tempfile.TemporaryDirectory(prefix=f"u16-{name}-") as directory:
        root = Path(directory)
        shutil.copytree(ROOT / "hooks", root / "hooks")
        shutil.copytree(ROOT / "agents", root / "agents")
        script = root / "tests/scripts/test-dispatch-gate.sh"
        script.parent.mkdir(parents=True)
        shutil.copy2(ROOT / "tests/scripts/test-dispatch-gate.sh", script)
        target = script if name == "lim17-double-call" else root / "hooks/dispatch-gate.py"
        target.write_text(mutated, encoding="utf-8")
        result = subprocess.run(["bash", str(script)], cwd=root, env=os.environ.copy(),
                                capture_output=True, text=True, timeout=480)
        print(f"MUTANT {name} EXIT={result.returncode}", flush=True)
        print(result.stdout, end="", flush=True)
        print(result.stderr, end="", flush=True)
        failures = {line.partition(":")[0].removeprefix("FAIL U16 ")
                    for line in result.stdout.split("\n") if line.startswith("FAIL ")}
        ok_set = failures == expected if mode == "exact" else expected <= failures
        if result.returncode != 1 or result.stderr != "" or not ok_set:
            raise SystemExit(
                f"REFUSE {name}: mode={mode} expected={sorted(expected)} "
                f"got={sorted(failures)} EXIT={result.returncode} "
                f"stderr={result.stderr!r}")
        print(f"MUTANT {name}: own-cause RED confirmed", flush=True)

print(f"u16-mutations: {len(MUTATIONS)}/{len(MUTATIONS)} own-cause RED confirmed", flush=True)
