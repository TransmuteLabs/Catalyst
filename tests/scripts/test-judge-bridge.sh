#!/usr/bin/env bash
# Стенд самопроверки моста судьи: предмет -- `scripts/judge-bridge.py
# --self-check` (офлайн: ни ssh, ни сети, ни чтения боевого дома проб --
# все зубы самопроверки гоняются на синтетических домах во временном
# каталоге). Красная сторона каждого зуба (мутации в код моста с
# восстановлением снимком) -- волна #199, зелёная живая приёмка моста --
# контроллер; стенд здесь охраняет ровно одно: самопроверка ДЕЙСТВИТЕЛЬНО
# прогнала заявленное число зубов.
#
# Коды по контракту агрегатора (tests/run-all.sh):
#   0 -- зелёный, ОДНОЙ строкой с числом зубов;
#   1 -- красный: дословный вывод самопроверки;
#   2 -- прибор недоступен (нет python3 / самопроверка ответила кодом 2);
#   3 -- НЕ ИЗМЕРЕНО: rc=0 без доказанного числа зубов -- ноль без числа
#        читался бы как пройденная приёмка, а молча выпавший зуб неотличим
#        от никогда не существовавшего (тот же принцип, что и гейт числа
#        стендов в run-all.sh).
#
# CONSTRAINT: ожидаемое число зубов объявлено ЗДЕСЬ и больше нигде --
# самопроверка печатает фактически прогнанное число, и расхождение в любую
# сторону это rc=3, а не зелёный.
set -u

EXPECTED_TEETH=9

if ! command -v python3 >/dev/null 2>&1; then
  printf 'ПРИБОР НЕДОСТУПЕН: нет python3\n' >&2
  exit 2
fi

HERE=$(cd "$(dirname "$0")" && pwd) || exit 2
ROOT=$(cd "$HERE/../.." && pwd) || exit 2
BRIDGE="$ROOT/scripts/judge-bridge.py"

if [ ! -f "$BRIDGE" ]; then
  printf 'ПРИБОР НЕДОСТУПЕН: нет scripts/judge-bridge.py\n' >&2
  exit 2
fi

OUT=$(python3 "$BRIDGE" --self-check 2>&1)
RC=$?

# Красный зуб -- находка: дословно, без пересказа.
if [ "$RC" -eq 1 ]; then
  printf 'КРАСЕН judge-bridge --self-check (rc=1):\n%s\n' "$OUT"
  exit 1
fi
# Сам прибор не в состоянии мерить -- не находка дерева.
if [ "$RC" -ne 0 ]; then
  printf 'ПРИБОР НЕДОСТУПЕН: judge-bridge --self-check rc=%s:\n%s\n' "$RC" "$OUT" >&2
  exit 2
fi

# rc=0 обязан ДОКАЗЫВАТЬ число зубов строкой вывода «зубов N».
TEETH=''
if [[ "$OUT" =~ зубов[[:space:]]+([0-9]+) ]]; then
  TEETH="${BASH_REMATCH[1]}"
fi
if [ -z "$TEETH" ]; then
  printf 'НЕ ИЗМЕРЕНО: rc=0 без доказанного числа зубов (в выводе нет «зубов N»):\n%s\n' "$OUT"
  exit 3
fi
if [ "$TEETH" -ne "$EXPECTED_TEETH" ]; then
  printf 'НЕ ИЗМЕРЕНО: зубов в выводе %s, а стенд ожидает %s (зуб выпал или прибавился):\n%s\n' \
    "$TEETH" "$EXPECTED_TEETH" "$OUT"
  exit 3
fi

printf 'ok judge-bridge --self-check: зубов %s, все зелены\n' "$TEETH"
exit 0
